_BY_CODE: dict[str, SubclassPower] = {one.code: one for one in POWERS}

#: Коды укладов - то, что загрузчик принимает у ветки.
POWER_KEYS: frozenset[str] = frozenset(_BY_CODE)


def has_power(code: str) -> bool:
    return code in _BY_CODE


def power(code: str) -> SubclassPower:
    return _BY_CODE[code]


def of(content: GameContent, character: Character) -> frozenset[str]:
    """Уклады всех взятых веток. Пусто - ветка не взята или ничего не даёт.

    Содержимое переживает персонажа: уклад, которого в реестре больше нет, сюда
    не попадает (``Claude.md``, правило 8).
    """
    return frozenset(
        one.power
        for one in subclass_rules.taken(content, character)
        if one.power and one.power in _BY_CODE
    )
