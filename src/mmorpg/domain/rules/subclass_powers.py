"""Уклад ветки: чем специализация меняет сам бой, а не числа в нём.

ЗАЧЕМ. Ветка давала три вещи: умение, свёрток прибавок и правку классовой сетки
(ADR 0074). Умение - одно из сорока, прибавки - проценты, сетка - проценты; и
потому Некромант отличался от Пиромана тем, каким родом урона бьёт, а не тем,
как за него играют. «Кем ты стал» обязано менять то, ЧТО ТЫ ДЕЛАЕШЬ В СВОЙ ХОД.

Поэтому у ветки есть **уклад** - правило, которое движок исполняет весь бой:
некромант поднимает павших и тянет из них жизнь, бард кладёт своё усиление на
весь отряд, палач добивает и возвращает себе ход, заслон вызывает удар на себя.
Укладов шестнадцать на всю игру, и ветки их делят: Некромант и Костоправ оба
поднимают павших, а различаются умением, прибавками и сеткой.

ЧТО УКЛАД НЕ ДЕЛАЕТ. Не даёт кнопки и не просит нажатия: у ветки нет своего
хода, у неё есть своё правило. Кнопку ветки даёт её умение, и оно лежит в
панели наравне со всеми (ADR 0067).

КАК ЭТО ОБЪЯВЛЯЕТСЯ. ``power`` в ``subclasses.toml`` - код отсюда. Величины
уклада живут ЗДЕСЬ, а не в содержимом: уклад - это правило, и правило одно для
всех, кто его получил. Числа ветки - это её ``modifiers``.

ВЗЯТОЕ СКЛАДЫВАЕТСЯ. Ветки берут по одной на ступень, и уклады всех трёх
работают разом: Оккультист, ставший Псиоником, ставший Иллюзионистом, держит
три правила, а не последнее.
"""

