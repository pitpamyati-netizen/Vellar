"""Связка: умение, которое отвечает на то, что уже висит на цели.

ЗАЧЕМ. Шесть боевых слотов и сорок изученных мест - но панель собиралась один
раз и навсегда, потому что собирать её было нечем: шесть самых сильных ударов
били сильнее любых шести других. Связка и есть то, ради чего панель
пересобирают: умение, отвечающее на состояние, бьёт заметно сильнее, но только
если в панели лежит и то, чем это состояние вешают.

КАК. У боевого умения бывает ``answers`` - имя состояния (``entities/statuses``).
Удар по цели, на которой это состояние висит, бьёт на ``DAMAGE_BONUS`` процентов
сильнее, и всё, что этот удар накладывает, держится на ход дольше.

НИЧЕГО НОВОГО ИГРОК НЕ СЧИТАЕТ. Связка стоит на состояниях, которые в игре уже
есть и которые уже называются вслух: «цель истекает кровью» говорит боевой
экран, а не скрытый счётчик. Тегов, следа и разгона в бою нет и не появилось
(ADR 0066) - есть кровь, огонь и яд, которые слышно.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Не порядком нажатий и не обязательной цепочкой: связка
никого ни к чему не принуждает, и умение без своего состояния работает как
работало. Она только делает так, что шесть слотов - это выбор.
"""

from __future__ import annotations

from mmorpg.domain.entities.combat import Combatant
from mmorpg.domain.entities.content import Skill
from mmorpg.domain.entities.statuses import StatusKind, status_spec

#: На сколько процентов сильнее бьёт умение, ответившее на состояние.
#: Шестьдесят: меньше не окупает слот, потраченный на то, чем состояние вешают,
#: а больше превращает свободный выбор в единственно верный.
DAMAGE_BONUS = 60.0

#: На сколько ходов дольше держится то, что наложил ответивший удар.
DURATION_BONUS = 1


def answered(skill: Skill, target: Combatant) -> bool:
    """Сработала ли связка: висит ли на цели то, на что умение отвечает."""
    return skill.answers is not None and target.effects.has(skill.answers)


def damage_factor(skill: Skill, target: Combatant) -> float:
    """Во сколько раз связка усиливает удар этого умения по этой цели."""
    return 1.0 + DAMAGE_BONUS / 100.0 if answered(skill, target) else 1.0


def answer_word(kind: StatusKind) -> str:
    """Состояние, на которое отвечает умение, - словом игрока."""
    return status_spec(kind).name


def demand_line(skill: Skill) -> str:
    """Чем это умение усиливают. Пусто - оно ни на что не отвечает."""
    if skill.answers is None:
        return ""
    return (
        f"Связка: по цели, на которой держится «{answer_word(skill.answers)}», "
        f"бьёт на {round(DAMAGE_BONUS)} процентов сильнее."
    )
