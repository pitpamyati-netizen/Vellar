"""Кривые, общие для нескольких правил.

Здесь лежит то, что считают в двух местах и что обязано считаться одинаково.
Пока это одна функция - убывающая отдача, - и вынесена она сюда ровно потому,
что её понадобилось звать и из ``rules/stats`` (крит, уклонение, точность), и из
``rules/modifiers`` (лечение по классовой сетке, ADR 0068). Копия формулы в двух
файлах однажды разъезжается; общий модуль без зависимостей - нет.
"""

from __future__ import annotations


def softened(raw: float, softener: float, ceiling: float) -> float:
    """Убывающая отдача: ``ceiling * raw / (raw + softener)``.

    Гладкая кривая без ступеней и без стены: первые очки характеристики стоят
    дорого, поздние - дёшево, и предел не достигается никогда (ADR 0058).
    Значение отрицательного ``raw`` - ноль: характеристика в минусе не даёт
    отрицательного крита, она просто не даёт ничего.
    """
    if raw <= 0.0 or softener <= 0.0:
        return 0.0
    return ceiling * raw / (raw + softener)
